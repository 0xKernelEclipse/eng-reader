/**
 * Offline English -> Arabic School & Everyday Dictionary
 *
 * Designed for 100% offline-first operation:
 * - Curated standard, clear student Arabic meanings (Egyptian/standard friendly)
 * - User custom meanings saved in localStorage take top priority
 * - Smart morphology & lemmatization (plurals, tenses, suffixes, irregular verbs)
 */

function readCustomMeanings(): Record<string, string> {
  if (typeof window === "undefined" || !("localStorage" in window)) return {};
  try {
    const raw = localStorage.getItem("reader-custom-meanings");
    if (!raw) return {};
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

